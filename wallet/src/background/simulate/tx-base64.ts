/**
 * Encodes byte arrays as base64 for RPC simulate payloads and explorer URLs.
 * Does not build URLs or perform RPC calls.
 */
export function bytesToBase64(bytes: Uint8Array): string {
  let binary = "";
  const chunk = 0x8000;
  for (let i = 0; i < bytes.length; i += chunk) {
    binary += String.fromCharCode(...bytes.subarray(i, i + chunk));
  }
  return btoa(binary);
}
